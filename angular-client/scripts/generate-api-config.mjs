import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const envPath = resolve(import.meta.dirname, '../../.env.local');
const useWorkerProxy = process.argv.includes('--worker');
let apiBaseUrl = useWorkerProxy ? '/api' : process.env.VITE_API_BASE_URL;

if (!apiBaseUrl) {
  apiBaseUrl = 'http://localhost:5261/api';
  try {
    const entry = readFileSync(envPath, 'utf8')
      .split(/\r?\n/)
      .find((line) => line.startsWith('VITE_API_BASE_URL='));
    if (entry) apiBaseUrl = entry.slice('VITE_API_BASE_URL='.length).trim();
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

if (!useWorkerProxy && !/^https?:\/\//.test(apiBaseUrl)) {
  throw new Error('VITE_API_BASE_URL must be an absolute http(s) URL.');
}

const target = resolve(import.meta.dirname, '../src/app/core/api.local.ts');
writeFileSync(target, `// Generated by generate-api-config.mjs. Do not commit.\nexport const apiBaseUrl = ${JSON.stringify(apiBaseUrl)};\n`, 'utf8');
